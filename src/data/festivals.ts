/**
 * Intelligent Calendar Checker:
 * Calculates day difference from current system date.
 * - Detects festivals TODAY (daysDiff = 0)
 * - Detects festivals TOMORROW (daysDiff = 1)
 * - Detects festivals UPCOMING within 2-7 days
 * - Detects nearest festival
 */
export function getFestivalAlert(currentDate = new Date()): FestivalAlert {
  const curYear = currentDate.getFullYear();
  const currentMidnight = new Date(curYear, currentDate.getMonth(), currentDate.getDate(), 0, 0, 0, 0);

  // Map festivals to upcoming occurrences with accurate day difference
  interface Candidate {
    festival: Festival;
    daysDiff: number;
  }

  const candidates: Candidate[] = FESTIVALS.map((fest) => {
    // Check this year's date
    const dateThisYear = new Date(curYear, fest.month - 1, fest.day, 0, 0, 0, 0);
    let diffDays = Math.round((dateThisYear.getTime() - currentMidnight.getTime()) / (24 * 60 * 60 * 1000));

    // If already passed in current year, calculate for next year
    if (diffDays < 0) {
      const dateNextYear = new Date(curYear + 1, fest.month - 1, fest.day, 0, 0, 0, 0);
      diffDays = Math.round((dateNextYear.getTime() - currentMidnight.getTime()) / (24 * 60 * 60 * 1000));
    }

    return { festival: fest, daysDiff: diffDays };
  });

  // Sort ascending by closest days difference
  candidates.sort((a, b) => a.daysDiff - b.daysDiff);

  // 1. Is any festival TODAY?
  const todayMatch = candidates.find((c) => c.daysDiff === 0);
  if (todayMatch) {
    return {
      festival: todayMatch.festival,
      status: 'today',
      daysDiff: 0,
      alertBadge: '🎉 आज का पावन पर्व',
      alertHeadline: `आज ${todayMatch.festival.nameHindi} का पावन पर्व है! सभी राइडर्स को शुभकामना संदेश भेजें`,
      alertDescription: `आज यह महापर्व मनाया जा रहा है। अपने कर्मठ राइडर्स को तुरंत हार्दिक बधाई संदेश भेजें!`,
    };
  }

  // 2. Is any festival TOMORROW?
  const tomorrowMatch = candidates.find((c) => c.daysDiff === 1);
  if (tomorrowMatch) {
    return {
      festival: tomorrowMatch.festival,
      status: 'tomorrow',
      daysDiff: 1,
      alertBadge: '🔔 कल का परब (अग्रिम संदेश)',
      alertHeadline: `कल ${tomorrowMatch.festival.nameHindi} है! अभी से अग्रिम शुभकामना संदेश भेजें (Advance Greetings Available)`,
      alertDescription: `कल यह पर्व मनाया जाएगा! पूर्व-संध्या पर सभी राइडर्स को अग्रिम शुभकामनाएं भेजें।`,
    };
  }

  // 3. Is any festival upcoming within next 2-7 days?
  const upcomingMatch = candidates.find((c) => c.daysDiff >= 2 && c.daysDiff <= 7);
  if (upcomingMatch) {
    return {
      festival: upcomingMatch.festival,
      status: 'upcoming',
      daysDiff: upcomingMatch.daysDiff,
      alertBadge: '🗓️ आगामी पर्व',
      alertHeadline: `🗓️ आगामी पर्व: ${upcomingMatch.festival.nameHindi} (${upcomingMatch.daysDiff} दिन बाद)!`,
      alertDescription: `${upcomingMatch.festival.dateLabel} — राइडर्स के लिए उत्सव का संदेश तैयार है।`,
    };
  }

  // 4. Fallback to nearest upcoming festival
  const nearest = candidates[0] || { festival: FESTIVALS[0], daysDiff: 0 };
  return {
    festival: nearest.festival,
    status: 'nearest',
    daysDiff: nearest.daysDiff,
    alertBadge: '✨ पावन पर्व कैलेंडर',
    alertHeadline: `${nearest.festival.nameHindi} (${nearest.festival.dateLabel})`,
    alertDescription: nearest.festival.description,
  };
}

/**
 * Automatically detects active or nearest upcoming festival based on current system date.
 * Kept backwards-compatible with existing callers.
 */
export function getActiveOrNearestFestival(currentDate = new Date()): Festival {
  const alert = getFestivalAlert(currentDate);
  return alert.festival;
}

/**
 * Prepares the formatted greeting message for WhatsApp or SMS with rider name inserted
 * and dynamic Hub / Business Signature replacement.
 */
export function formatFestivalGreeting(
  template: string,
  riderName: string,
  userHubSignature?: string
): string {
  let message = template.replace(/{riderName}/g, riderName.trim());
  const signature = (userHubSignature && userHubSignature.trim()) 
    ? userHubSignature.trim() 
    : 'कूरियर डिलीवरी टीम';

  // Replace explicit placeholder {userHubSignature} or {hubSignature} if present
  message = message.replace(/{userHubSignature}|{hubSignature}/g, signature);

  // Dynamically replace the bottom signature line with that specific user's assigned Hub Signature:
  // e.g. replacing trailing `\n\n- ...` with `\n\n- {userHubSignature || 'कूरियर डिलीवरी टीम'}`
  const signatureRegex = /(?:\r?\n)+-\s*[^\r\n]+$/;
  if (signatureRegex.test(message)) {
    message = message.replace(signatureRegex, `\n\n- ${signature}`);
  } else {
    message = `${message}\n\n- ${signature}`;
  }

  return message;
}

/**
 * Builds direct WhatsApp URL for a rider.
 */
export function buildWhatsAppGreetingUrl(phone: string, message: string): string {
  const clean = phone.replace(/\D/g, '').slice(-10);
  return `https://wa.me/91${clean}?text=${encodeURIComponent(message)}`;
}

/**
 * Builds direct SMS broadcast URL for a rider.
 */
export function buildSmsGreetingUrl(phone: string, message: string): string {
  const clean = phone.replace(/\D/g, '').slice(-10);
  return `sms:+91${clean}?body=${encodeURIComponent(message)}`;
}
